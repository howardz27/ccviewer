"""Shared, dependency-free fragments for application and guide builds."""
import html
import json
import re
from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parent
LANGS = [('en', 'English'), ('zh', '中文'), ('ja', '日本語'), ('ko', '한국어'),
         ('es', 'Español'), ('fr', 'Français'), ('de', 'Deutsch'),
         ('pt', 'Português'), ('ru', 'Русский'), ('hi', 'हिन्दी')]


def public_slug(slug):
    """Match Cloudflare auto-trailing-slash routing for individual HTML files."""
    return slug[:-5] if slug.endswith('.html') else slug


def analytics(lang):
    config = json.loads((ROOT / 'analytics.json').read_text(encoding='utf-8'))
    project_id = config['projectId']
    if project_id and not re.fullmatch(r'[a-zA-Z0-9]+', project_id):
        raise ValueError('Clarity projectId must be alphanumeric')
    js = (ROOT / 'src/analytics.js').read_text(encoding='utf-8')
    js = js.replace('__CONFIG__', json.dumps(config))
    return '<script>\n' + js + '\n</script>'


def language_links(lang, slug=''):
    links = []
    for code, label in LANGS:
        url = '/claude-code-session-viewer/' + ('' if code == 'en' else code + '/') + public_slug(slug)
        current = ' aria-current="page"' if code == lang else ''
        links.append(f'<a href="{url}" hreflang="{code}" lang="{code}"{current}>{label}</a>')
    return '<nav aria-label="Language" class="site-languages">' + ' · '.join(links) + '</nav>'


def resources(lang):
    ui = json.loads((ROOT / 'src/i18n' / f'{lang}.json').read_text(encoding='utf-8'))['ui']
    title = html.escape(ui['resourcesTitle'])
    return f'''<aside class="site-resources"><h2>{title}</h2>
<ul>
<li><a href="https://code.claude.com/docs/en/how-claude-code-works" target="_blank" rel="noopener noreferrer">Claude Code — {html.escape(ui['resourcesDocs'])}</a></li>
<li><a href="https://code.claude.com/docs/en/cli-reference" target="_blank" rel="noopener noreferrer">Claude Code — CLI</a></li>
<li><a href="https://jsonlines.org/" target="_blank" rel="noopener noreferrer">JSON Lines (.jsonl)</a></li>
<li><a href="https://github.com/howardz27/ccviewer/issues" target="_blank" rel="noopener noreferrer">GitHub — {html.escape(ui['resourcesIssues'])}</a></li>
</ul></aside>'''


def build_routes(guide_slugs, article_dates, published_date):
    """Generate permanent aliases and a sitemap containing final 200 URLs only."""
    base = '/claude-code-session-viewer/'
    redirects = [
        '# Generated by claude-code-session-viewer/build.py. Do not edit by hand.',
        f'/ {base} 301',
        f'/index.html {base} 301',
        f'/index {base} 301',
    ]
    ns = 'http://www.sitemaps.org/schemas/sitemap/0.9'
    ET.register_namespace('', ns)
    sitemap = ET.Element('{' + ns + '}urlset')

    def add_url(path, date, priority):
        entry = ET.SubElement(sitemap, 'url')
        ET.SubElement(entry, 'loc').text = 'https://ccviewer.top' + path
        ET.SubElement(entry, 'lastmod').text = date
        ET.SubElement(entry, 'changefreq').text = 'monthly'
        ET.SubElement(entry, 'priority').text = priority

    for lang, _ in LANGS:
        prefix = base + ('' if lang == 'en' else lang + '/')
        add_url(prefix, published_date, '1.0' if lang == 'en' else '0.9')
        for alias in [prefix.rstrip('/'), prefix + 'index.html', prefix + 'index']:
            redirects.append(f'{alias} {prefix} 301')
        for slug in guide_slugs:
            path = prefix + public_slug(slug)
            add_url(path, article_dates.get(slug, published_date), '0.7')
            redirects.append(f'{prefix}{slug} {path} 301')
            redirects.append(f'{path}/ {path} 301')

    (ROOT.parent / '_redirects').write_text('\n'.join(redirects) + '\n', encoding='utf-8')
    # Keep output compatible with the project's Python 3.8 build instructions.
    from xml.dom import minidom
    xml = minidom.parseString(ET.tostring(sitemap, encoding='utf-8')).toprettyxml(indent='  ', encoding='UTF-8')
    (ROOT.parent / 'sitemap.xml').write_bytes(xml)
