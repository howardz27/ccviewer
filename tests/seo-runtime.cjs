// Verify SEO survives hydration and the public reading fixture matches its guide.
const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const source = fs.readFileSync('claude-code-session-viewer/src/template.html', 'utf8');
const parser = source.slice(source.indexOf('function parse('), source.indexOf('function toolArgPreview('));
const sample = fs.readFileSync('assets/example-session.jsonl', 'utf8');
const context = {sample};
vm.createContext(context);
vm.runInContext(parser + '\nvar parsed = parse(sample); var summary = summarize(parsed.entries);', context);
assert.equal(context.parsed.bad, 0);
assert.equal(context.parsed.entries.length, 4);
assert.equal(context.summary.counts.user, 1);
assert.equal(context.summary.counts.tool, 1);
assert.equal(context.summary.tokens.in, 120);
assert.equal(context.summary.tokens.out, 45);
const titleLogic = source.slice(source.indexOf('function curName('), source.indexOf('// 切换语言 / 重新渲染'));
const titleContext = {document: {title: 'CCViewer SEO title'}, HOME_TITLE: 'CCViewer SEO title',
  CUR: null, $: () => ({textContent: ''}), t: key => key};
vm.createContext(titleContext);
vm.runInContext(titleLogic + '\napplyFname();', titleContext);
assert.equal(titleContext.document.title, titleContext.HOME_TITLE, 'Hydration must retain the indexed title');
titleContext.CUR = {name: 'example.jsonl', sum: {title: 'Fictional demo'}};
vm.runInContext('applyFname();', titleContext);
assert.equal(titleContext.document.title, 'Fictional demo · viewerSuffix');
titleContext.CUR = null;
vm.runInContext('applyFname();', titleContext);
assert.equal(titleContext.document.title, titleContext.HOME_TITLE);
console.log('SEO runtime: landing title preserved; fictional sample parsing and documented usage passed.');
context.CUR = {entries: context.parsed.entries, sum: context.summary, name: 'example-session.jsonl'};
context.SHOW_TOOL = true;
context.SHOW_THINK = true;
context.fmtTime = value => value;
context.num = value => String(value);
context.t = key => key;
const markdownLogic = source.slice(source.indexOf('const resultText='), source.indexOf('function exportMd('));
vm.runInContext(markdownLogic + '\nvar markdown = buildMd();', context);
assert.match(context.markdown, /## Summary/);
assert.match(context.markdown, /fictional demo/);
assert.match(context.markdown, /in 120 \/ out 45/);
assert.match(context.markdown, /README\.md/);
console.log('Sample Markdown: prompt, reply, tool parameters and token counts passed.');
